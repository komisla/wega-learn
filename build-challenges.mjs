// build-challenges.mjs — bundles challenges/world*.json into challenges/challenges.js
// so the app works when opening index.html directly via file:// (no fetch/CORS).
// Run:  node build-challenges.mjs
import { readFileSync, writeFileSync } from 'fs';
const files = ['world1-xpath.json','world2-flwor.json','world3-xslt.json','world4-wega.json'];
const data = {};
for (const f of files){
  const arr = JSON.parse(readFileSync('challenges/'+f,'utf8'));
  const w = arr[0].world;
  data['world'+w] = arr;
}
const out = '// AUTO-GENERATED by build-challenges.mjs — do not edit by hand.\n'
  + '// Source of truth: challenges/world*.json. Rebuild with: node build-challenges.mjs\n'
  + 'window.CHALLENGES = ' + JSON.stringify(data, null, 2) + ';\n';
writeFileSync('challenges/challenges.js', out);
console.log('Wrote challenges/challenges.js with worlds:', Object.keys(data).join(', '),
  '| total challenges:', Object.values(data).reduce((n,a)=>n+a.length,0));
