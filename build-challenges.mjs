// build-challenges.mjs — bundles challenges/ JSON files into challenges/challenges.js
// so the app works when opening index.html directly via file:// (no fetch/CORS).
// Run:  node build-challenges.mjs
import { readFileSync, writeFileSync } from 'fs';

// Challenge worlds
const worldFiles = [
  'world1-xpath.json',
  'world2-flwor.json',
  'world3-xslt.json',
  'world4-wega.json',
  'world5-existdb.json'
];
const data = {};
for (const f of worldFiles){
  const arr = JSON.parse(readFileSync('challenges/'+f,'utf8'));
  const w = arr[0].world;
  data['world'+w] = arr;
}

// Concept cards
const concepts = JSON.parse(readFileSync('challenges/concepts.json','utf8'));

const out = '// AUTO-GENERATED by build-challenges.mjs — do not edit by hand.\n'
  + '// Source of truth: challenges/world*.json + concepts.json. Rebuild with: node build-challenges.mjs\n'
  + 'window.CHALLENGES = ' + JSON.stringify(data, null, 2) + ';\n'
  + 'window.CONCEPTS = ' + JSON.stringify(concepts, null, 2) + ';\n';
writeFileSync('challenges/challenges.js', out);

const total = Object.values(data).reduce((n,a)=>n+a.length,0);
console.log('Wrote challenges/challenges.js');
console.log('  Worlds:', Object.keys(data).join(', '), '| Total challenges:', total);
console.log('  Concept cards:', Object.keys(concepts).length);
